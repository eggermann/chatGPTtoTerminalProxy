#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
TOOL_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
TARGET_INPUT="${1:-$(pwd)}"
ENABLE_PROMPT_CONCATOR="false"
START_WATCHER="true"

die() {
  echo "$*" >&2
  exit 1
}

usage() {
  cat <<'EOF'
Usage:
  parasit.sh setup [path]
  parasit.sh setup --prompt-concator [path]
  parasit.sh setup --no-watch [path]
EOF
}

resolve_target_dir() {
  local input="$1"

  if [ -e "$input" ]; then
    if [ -d "$input" ]; then
      cd -- "$input" && pwd
    else
      cd -- "$(dirname -- "$input")" && pwd
    fi
  else
    die "Target path not found: $input"
  fi
}

project_name_from_dir() {
  basename "$1"
}

write_vscode_settings() {
  local project_dir="$1"
  local vscode_dir="$project_dir/.vscode"
  local settings_file="$vscode_dir/settings.json"

  mkdir -p "$vscode_dir"
  if [ ! -f "$settings_file" ]; then
    cat > "$settings_file" <<'EOF'
{
  "files.autoSave": "afterDelay",
  "files.autoSaveDelay": 200,
  "editor.formatOnSave": true,
  "files.trimTrailingWhitespace": true,
  "files.insertFinalNewline": true
}
EOF
  fi
}

write_codex_config() {
  local project_dir="$1"
  local prompt_concator_enabled="$2"
  local inbox_dir="$project_dir/.codex-inbox"
  local config_file="$inbox_dir/config.json"

  mkdir -p "$inbox_dir"
  if [ ! -f "$config_file" ]; then
    cat > "$config_file" <<EOF
{
  "workflow": "chat-first",
  "approvalLevel": "standard",
  "defaultButton": "Run",
  "notifyChatGPT": true,
  "autocommit": false,
  "runMode": "auto",
  "activateWatchOnSave": {
    "chat": true,
    "commands": true
  },
  "promptConcator": {
    "enabled": $prompt_concator_enabled,
    "prompt": "Project context generated by prompt-concator. Use these files as the current source of truth.",
    "textEdit": false,
    "ignoreGitignore": false
  }
}
EOF
    return 0
  fi

  if command -v python3 >/dev/null 2>&1; then
    python3 - "$config_file" "$prompt_concator_enabled" <<'PY'
import json
import sys
from pathlib import Path

path = Path(sys.argv[1])
enabled = sys.argv[2].lower() == "true"
try:
    data = json.loads(path.read_text())
except Exception:
    data = {}

data.setdefault("workflow", "chat-first")
data.setdefault("approvalLevel", "standard")
data.setdefault("defaultButton", "Run")
data.setdefault("notifyChatGPT", True)
data.setdefault("autocommit", False)
data.setdefault("runMode", "auto")
data.setdefault("activateWatchOnSave", {"chat": True, "commands": True})

prompt = data.get("promptConcator", {})
if not isinstance(prompt, dict):
    prompt = {}
prompt.setdefault("prompt", "Project context generated by prompt-concator. Use these files as the current source of truth.")
prompt.setdefault("textEdit", False)
prompt.setdefault("ignoreGitignore", False)
prompt["enabled"] = enabled or bool(prompt.get("enabled", False))
data["promptConcator"] = prompt

path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
PY
  fi
}

write_prompt_config() {
  local project_dir="$1"
  local prompt_file="$project_dir/prompt.config.json"

  if [ -f "$prompt_file" ]; then
    return 0
  fi

  if [ -f "$project_dir/app.py" ] || [ -f "$project_dir/requirements.txt" ]; then
    cat > "$prompt_file" <<'EOF'
{
  "excludeFolders": [
    "node_modules",
    ".git",
    ".venv",
    "venv",
    "__pycache__",
    "data/generated_assets"
  ],
  "excludeFiles": [
    "input-prompt.txt",
    "*.log"
  ],
  "patterns": [
    { "src": "./README.md" },
    { "src": "./app.py" },
    { "src": "./requirements.txt" },
    { "src": "./roules.md" },
    { "src": "./src/**/*.py" }
  ],
  "textEdit": false,
  "ignoreGitignore": false
}
EOF
    return 0
  fi

  cat > "$prompt_file" <<'EOF'
{
  "excludeFolders": ["node_modules", ".git", "dist", "build", "out"],
  "excludeFiles": ["input-prompt.txt", "*.log"],
  "patterns": [
    { "src": "./README.md" },
    { "src": "./src/**/*.*" },
    { "src": "./docs/**/*.*" }
  ],
  "textEdit": false,
  "ignoreGitignore": false
}
EOF
}

parse_args() {
  local -a args=("$@")
  local filtered=()
  local item
  local i

  for ((i = 0; i < ${#args[@]}; i++)); do
    item="${args[$i]}"
    case "$item" in
      --prompt-concator)
        ENABLE_PROMPT_CONCATOR="true"
        ;;
      --no-watch)
        START_WATCHER="false"
        ;;
      -h|--help)
        usage
        exit 0
        ;;
      *)
        filtered+=("$item")
        ;;
    esac
  done

  if [ "${#filtered[@]}" -gt 0 ]; then
    TARGET_INPUT="${filtered[$(( ${#filtered[@]} - 1 ))]}"
  fi
}

parse_args "$@"

PROJECT_DIR="$(resolve_target_dir "$TARGET_INPUT")"
PROJECT_NAME="$(project_name_from_dir "$PROJECT_DIR")"

write_vscode_settings "$PROJECT_DIR"
write_prompt_config "$PROJECT_DIR"
write_codex_config "$PROJECT_DIR" "$ENABLE_PROMPT_CONCATOR"

echo "Bootstrap target: $PROJECT_DIR"
echo "Project name: $PROJECT_NAME"
echo "prompt-concator: $ENABLE_PROMPT_CONCATOR"
echo "watcher: $START_WATCHER"

if [ "$START_WATCHER" = "true" ]; then
  exec "$TOOL_ROOT/parasit.sh" fresh "$PROJECT_DIR"
fi

echo "Workspace prepared."
